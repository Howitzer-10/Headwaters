"""The per-host setup pages, generated from the installer (HDW-407).

A page is a projection of one adapter: the files ``headwaters install --host <id>`` writes, what
the user still has to do, and the templates the install is built from. Nothing here reads a real
profile - the render context uses placeholder folders and any path that escapes them is shown as
``<path>`` - so the committed pages are byte-identical on every machine and the release gate can
tell when a template changed without the docs being regenerated.
"""

from __future__ import annotations

import re
from pathlib import Path

from headwaters.core.daemon_info import token_path
from headwaters.core.mcp_launch import McpLaunch
from headwaters.installer.base import HostAdapter
from headwaters.installer.context import DEFAULT_PORT, Context
from headwaters.installer.hosts import all_adapters
from headwaters.installer.plan import FileChange

__all__ = [
    "DOCS_DIR",
    "GENERATED_NOTE",
    "INDEX_NAME",
    "display",
    "display_context",
    "hosts_dir",
    "page_name",
    "render_all",
    "render_host_page",
    "render_index",
    "stale_pages",
    "write_pages",
]

DOCS_DIR = "docs"
HOSTS_DIR = "hosts"
INDEX_NAME = "index.md"
GENERATED_NOTE = (
    "<!-- Generated by `headwaters release-docs` from the host adapter and the installer"
    " templates. Do not edit by hand: change the adapter or the template, then regenerate. -->"
)

_LAUNCHER = "headwaters-mcp"
_MARKERS = {
    "project": "_hw_project_",
    "home": "_hw_home_",
    "state": "_hw_state_",
    "appdata": "_hw_appdata_",
}
_ABSOLUTE = re.compile(r"(?<![\w:/>])(?:[A-Za-z]:[\\/]|/)[^\s\"'`|<>]*[\\/][^\s\"'`|<>]+")
_AFTER_TOKEN = re.compile(r"(<(?:project|home|state|appdata)>)[\\/]+")


def display_context() -> Context:
    """The fixed context every page is rendered from: no machine path, no real profile."""
    return Context(
        project=Path(_MARKERS["project"]),
        home=Path(_MARKERS["home"]),
        state=Path(_MARKERS["state"]),
        launch=McpLaunch("script", _LAUNCHER),
        port=DEFAULT_PORT,
        appdata_override=Path(_MARKERS["appdata"]),
    )


def display(text: str, ctx: Context | None = None) -> str:
    """Machine-independent text: known folders become tokens, any other absolute path ``<path>``."""
    chosen = ctx or display_context()
    out = str(text).replace(str(token_path()), "<state>/daemon.token")
    out = out.replace(token_path().as_posix(), "<state>/daemon.token")
    prefixes = [
        (chosen.project, "<project>"),
        (chosen.appdata, "<appdata>"),
        (chosen.state, "<state>"),
        (chosen.home, "<home>"),
    ]
    for prefix, token in sorted(prefixes, key=lambda item: len(str(item[0])), reverse=True):
        out = out.replace(str(prefix), token)
        out = out.replace(prefix.as_posix(), token)
    out = _AFTER_TOKEN.sub(r"\1/", out)
    out = _ABSOLUTE.sub("<path>", out)
    # Windows and POSIX separators must not leak into a committed page.
    return out.replace("\\", "/")


def hosts_dir(root: Path) -> Path:
    return root / DOCS_DIR / HOSTS_DIR


def page_name(adapter: HostAdapter) -> str:
    return f"{adapter.id}.md"


def render_all() -> dict[str, str]:
    """Every generated page, keyed by the repo-relative POSIX path it is committed at."""
    ctx = display_context()
    pages = {f"{DOCS_DIR}/{HOSTS_DIR}/{INDEX_NAME}": render_index(ctx)}
    for adapter in all_adapters():
        pages[f"{DOCS_DIR}/{HOSTS_DIR}/{page_name(adapter)}"] = render_host_page(adapter, ctx)
    return pages


def render_index(ctx: Context) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "# Host setup",
        "",
        "Headwaters runs as one local gateway on this machine. Each host talks to it over the",
        "same OpenAI-compatible endpoint, so switching hosts never means reconfiguring a model.",
        "",
        "| Host | Scope | Setup page |",
        "| --- | --- | --- |",
    ]
    for adapter in all_adapters():
        scope = "user profile" if adapter.scope == "user" else "project folder"
        lines.append(f"| {adapter.title} | {scope} | [{adapter.id}]({page_name(adapter)}) |")
    base = ctx.base_url
    launch = ctx.launch.command
    token = display(str(token_path()), ctx)
    lines += [
        "",
        "## What every host gets",
        "",
        f"- Gateway base URL: `{base}`; MCP over stdio, launched by `{launch}`.",
        "- Model ids: `auto`, `free` and `local` - the same names `headwaters pick` and "
        "`--model` use.",
        f"- A gateway token in `{token}`; a host asks for it once.",
        "",
        "## Before any host",
        "",
        "1. `headwaters status` - the daemon answers on the gateway port.",
        "2. `headwaters doctor` - GPU, models and keys are healthy.",
        "3. `headwaters install --host <id>` - shows the diff, then writes it.",
        "",
        "If a host is already configured and something looks wrong, run",
        "`headwaters doctor --host <id>`; it reads the host's own config back and names the stale",
        "field. Nothing is written without `--yes` (or a yes at the prompt).",
        "",
        "Something broken that these pages do not cover: [troubleshooting](../TROUBLESHOOTING.md).",
        "",
    ]
    return "\n".join(lines)


def _file_table(changes: list[FileChange], ctx: Context) -> list[str]:
    lines = ["| File | What the install does |", "| --- | --- |"]
    for item in changes:
        what = item.kind
        if item.note:
            what = f"{what} - {display(item.note, ctx)}"
        lines.append(f"| `{display(str(item.path), ctx)}` | {what} |")
    return lines


def render_host_page(adapter: HostAdapter, ctx: Context) -> str:
    changes = adapter.plan(ctx)
    notes = adapter.notes(ctx)
    scope = (
        "This host keeps its config in your user profile."
        if adapter.scope == "user"
        else "This host keeps its config in the project folder, so the setup travels with the repo."
    )
    lines = [
        GENERATED_NOTE,
        "",
        f"# {adapter.title}",
        "",
        scope,
        "",
        "## Install",
        "",
        "```",
        f"headwaters install --host {adapter.id}",
        "```",
        "",
        "The installer prints the diff first and writes only after a yes; `--dry-run` stops at the",
        "diff and `--json` prints the same plan as a document.",
        "",
        "## Files",
        "",
        *_file_table(changes, ctx),
        "",
        "## What you still do",
        "",
    ]
    lines += [f"- {display(note, ctx)}" for note in notes] or [
        "- Nothing: the install leaves this host ready."
    ]
    lines += [
        "",
        "## Templates behind this page",
        "",
        "The entries above are rendered from "
        + ", ".join(f"`{name}`" for name in adapter.template_names)
        + " in `headwaters/installer/templates/`, so this page and a real install cannot drift.",
        "",
        "## Check it",
        "",
        "```",
        f"headwaters doctor --host {adapter.id}",
        "```",
        "",
        "The doctor reads this host's own config back and reports a missing or stale entry; a",
        "clean report means the host is talking to the gateway.",
        "",
        "## Remove it",
        "",
        "```",
        f"headwaters uninstall --host {adapter.id}",
        "```",
        "",
        "The uninstall restores the backed-up file unless it was edited after the install; then it",
        "asks for `--force`.",
        "",
    ]
    return "\n".join(lines)


def stale_pages(root: Path) -> list[str]:
    """Generated pages that are missing or differ from what the installer would write now."""
    stale: list[str] = []
    for relative, wanted in render_all().items():
        path = root / relative
        if not path.is_file():
            stale.append(relative)
            continue
        if path.read_text(encoding="utf-8").replace("\r\n", "\n") != wanted:
            stale.append(relative)
    return stale


def write_pages(root: Path) -> list[str]:
    """Write the missing or stale pages with ``\\n`` only; return the paths actually written."""
    written: list[str] = []
    for relative, text in render_all().items():
        path = root / relative
        if path.is_file() and path.read_text(encoding="utf-8").replace("\r\n", "\n") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(relative)
    return written
