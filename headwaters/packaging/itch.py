"""The itch.io manifest (HDW-405): launch actions wired to the real CLI.

``.itch.toml`` sits at the payload root and every action runs ``uv`` from ``runtime/`` with
``uv run``, so the actions work before the user has ever opened a console: uv creates or repairs
the private virtualenv on first launch, exactly as the installer does.

Paths in the manifest are relative to the manifest's own folder (the itch app resolves them
there), and each action runs a command that ``headwaters --help`` lists. :func:`render_manifest`
is the single source of truth; ``packaging/itch/.itch.toml`` is that text byte for byte, and a
test compares them so the file can never drift.
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from headwaters.packaging.layout import Install

PLATFORM = "windows"
MARKER_NAME = ".itch.toml"

#: The payload root as the manifest sees it; only relative paths ever appear in the file.
PAYLOAD = Install.at(Path("."))

#: Extra host ids the installer knows; the tests check this against ``installer.hosts``.
INSTALL_HOSTS = (
    ("vscode", "VS Code"),
    ("cline", "Cline"),
    ("opencode", "OpenCode"),
    ("claude-desktop", "Claude Desktop"),
)


@dataclass(frozen=True)
class Action:
    """One ``[[actions]]`` entry."""

    name: str
    path: str
    args: tuple[str, ...]
    platform: str = PLATFORM

    def as_toml(self) -> str:
        args = ", ".join(_quote(arg) for arg in self.args)
        return (
            "[[actions]]\n"
            f"name = {_quote(self.name)}\n"
            f"path = {_quote(self.path)}\n"
            f"args = [{args}]\n"
            f"platform = {_quote(self.platform)}\n"
        )


def _quote(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def action_argv(*cli_args: str) -> tuple[str, ...]:
    """The argv tail every action shares: uv, the payload runtime, then the CLI arguments."""
    return (
        "run",
        "--frozen",
        "--no-dev",
        "--project",
        PAYLOAD.runtime.as_posix(),
        "headwaters",
        *cli_args,
    )


def actions() -> list[Action]:
    """The actions the itch app offers, in menu order."""
    path = PAYLOAD.uv.as_posix()
    entries = [
        Action("Open status page", path, action_argv("status", "--open")),
        Action("Doctor", path, action_argv("doctor")),
    ]
    for host, label in INSTALL_HOSTS:
        # --yes because a launch action has no one to answer the prompt: clicking the menu
        # entry is the consent, and `install` still prints the diff it would write first.
        entries.append(
            Action(
                f"Install for {label}",
                path,
                action_argv("install", "--host", host, "--yes"),
            )
        )
    return entries


def render_manifest() -> str:
    """The whole ``.itch.toml``; the committed file must equal this text."""
    header = (
        "# Generated by headwaters/packaging/itch.py (HDW-405). Do not edit by hand:\n"
        "# `uv run python -m pytest tests/test_packaging_artifacts.py` compares it.\n"
        "# Paths are relative to this file; each action runs the uv shipped in runtime/.\n"
    )
    return header + "\n" + "\n".join(action.as_toml() for action in actions())


def parse(text: str) -> dict[str, Any]:
    return tomllib.loads(text)


def read_manifest(root: Path | str) -> dict[str, Any]:
    return parse((Path(root) / MARKER_NAME).read_text(encoding="utf-8"))


def manifest_actions(root: Path | str) -> list[dict[str, Any]]:
    return list(read_manifest(root).get("actions", []))
